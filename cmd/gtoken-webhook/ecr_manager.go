// CopySecretToNamespace copies the ECR secret to a target namespace
func (em *ecrManager) CopySecretToNamespace(ctx context.Context, namespace string) error {
	start := time.Now()

	// Use exponential backoff for secret copy operations
	err := RetryWithBackoff(ctx, DefaultBackoffConfig(), func() error {
		return em.copySecretToNamespaceOnce(ctx, namespace)
	})

	duration := time.Since(start)
	if err != nil {
		em.metrics.RecordSecretCopy(namespace, "failure", duration)
		em.metrics.RecordSecretCopyError()
		return err
	}

	em.metrics.RecordSecretCopy(namespace, "success", duration)
	return nil
}

// copySecretToNamespaceOnce performs a single secret copy operation
func (em *ecrManager) copySecretToNamespaceOnce(ctx context.Context, namespace string) error {
	// Get the master secret from the gtoken namespace
	masterSecret, err := em.config.K8sClient.CoreV1().Secrets(em.config.GTokenNS).Get(ctx, em.config.ECRSecretName, metav1.GetOptions{})
	if err != nil {
		return fmt.Errorf("failed to get master ECR secret: %w", err)
	}

	// Create a copy of the secret for the target namespace
	copiedSecret := &corev1.Secret{
		ObjectMeta: metav1.ObjectMeta{
			Name:      em.config.ECRSecretName,
			Namespace: namespace,
			Labels: map[string]string{
				"app":         "gtoken-webhook",
				"type":        "ecr-secret",
				"copied-from": em.config.GTokenNS,
			},
			Annotations: masterSecret.Annotations, // Copy annotations including ecr-token-version
		},
		Type: masterSecret.Type,
		Data: masterSecret.Data,
	}

	// Try to create the secret, if it exists, update it
	_, err = em.config.K8sClient.CoreV1().Secrets(namespace).Create(ctx, copiedSecret, metav1.CreateOptions{})
	if err != nil {
		// If secret already exists, update it
		_, err = em.config.K8sClient.CoreV1().Secrets(namespace).Update(ctx, copiedSecret, metav1.UpdateOptions{})
		if err != nil {
			return fmt.Errorf("failed to create/update ECR secret in namespace %s: %w", namespace, err)
		}
	}

	// Label the namespace to track it as ECR-managed
	namespaceObj, err := em.config.K8sClient.CoreV1().Namespaces().Get(ctx, namespace, metav1.GetOptions{})
	if err != nil {
		return fmt.Errorf("failed to get namespace %s: %w", namespace, err)
	}

	// Add the ECR management label
	if namespaceObj.Labels == nil {
		namespaceObj.Labels = make(map[string]string)
	}
	namespaceObj.Labels["gtoken.doit-intl.com/ecr-managed"] = "true"

	_, err = em.config.K8sClient.CoreV1().Namespaces().Update(ctx, namespaceObj, metav1.UpdateOptions{})
	if err != nil {
		return fmt.Errorf("failed to label namespace %s: %w", namespace, err)
	}

	return nil
}

// ValidateSecret checks if a secret exists and is valid in a namespace
func (em *ecrManager) ValidateSecret(ctx context.Context, namespace string) (bool, error) {
	// Get the secret from the namespace
	secret, err := em.config.K8sClient.CoreV1().Secrets(namespace).Get(ctx, em.config.ECRSecretName, metav1.GetOptions{})
	if err != nil {
		return false, fmt.Errorf("failed to get ECR secret: %w", err)
	}

	// Check if it's a docker config secret
	if secret.Type != corev1.SecretTypeDockerConfigJson {
		return false, fmt.Errorf("secret is not a docker config json")
	}

	// Get the docker config data
	dockerConfigData, ok := secret.Data[".dockerconfigjson"]
	if !ok {
		return false, fmt.Errorf("secret does not contain .dockerconfigjson data")
	}

	// Parse the docker config
	var dockerCfg dockerConfig
	if err := json.Unmarshal(dockerConfigData, &dockerCfg); err != nil {
		return false, fmt.Errorf("invalid docker config json: %w", err)
	}

	// Check if it contains any ECR registry entries
	for registry := range dockerCfg.Auths {
		if strings.Contains(registry, ".dkr.ecr.") && strings.Contains(registry, ".amazonaws.com") {
			return true, nil
		}
	}

	return false, fmt.Errorf("no ECR registry entries found in docker config")
}

// StartTokenRefresh starts the background token refresh goroutine
func (em *ecrManager) StartTokenRefresh(ctx context.Context) error {
	go func() {
		// Immediately try to get a token and create the secret
		token, expiry, err := em.GetECRToken(ctx)
		if err != nil {
			log.Printf("Failed to refresh ECR token (initial): %v", err)
		} else {
			err = em.CreateMasterSecret(ctx, token)
			if err != nil {
				log.Printf("Failed to update master ECR secret (initial): %v", err)
			}
			err = em.UpdateTokenState(ctx, token, expiry)
			if err != nil {
				log.Printf("Failed to update token state ConfigMap (initial): %v", err)
			}
			err = em.RefreshAllNamespaces(ctx, token)
			if err != nil {
				log.Printf("Failed to propagate ECR token to all namespaces (initial): %v", err)
			}
			log.Printf("Successfully refreshed ECR token (initial), expires at: %v", expiry)
		}

		ticker := time.NewTicker(em.config.RefreshBuffer)
		defer ticker.Stop()

		for {
			select {
			case <-ctx.Done():
				return
			case <-em.stopChan:
				return
			case <-ticker.C:
				// Get a new ECR token
				token, expiry, err := em.GetECRToken(ctx)
				if err != nil {
					log.Printf("Failed to refresh ECR token: %v", err)
					continue
				}

				// Create/update the master secret with the new token
				err = em.CreateMasterSecret(ctx, token)
				if err != nil {
					log.Printf("Failed to update master ECR secret: %v", err)
					continue
				}

				// Update ConfigMap with token state for disaster recovery
				err = em.UpdateTokenState(ctx, token, expiry)
				if err != nil {
					log.Printf("Failed to update token state ConfigMap: %v", err)
					// Continue even if ConfigMap update fails
				}

				// Propagate the new token to all managed namespaces
				err = em.RefreshAllNamespaces(ctx, token)
				if err != nil {
					log.Printf("Failed to propagate ECR token to all namespaces: %v", err)
					// Continue even if propagation fails
				}

				log.Printf("Successfully refreshed ECR token, expires at: %v", expiry)

				// Calculate next refresh time (refresh before expiration)
				nextRefresh := time.Until(expiry) - em.config.RefreshBuffer
				if nextRefresh > 0 {
					ticker.Reset(nextRefresh)
				}
			}
		}
	}()

	return nil
}

// Stop stops the token refresh goroutine
func (em *ecrManager) Stop() {
	if !em.stopped {
		close(em.stopChan)
		em.stopped = true
	}
}

// RefreshAllNamespaces updates ECR secrets in all tracked namespaces
func (em *ecrManager) RefreshAllNamespaces(ctx context.Context, _ string) error {
	// Find all namespaces with the ECR management label
	namespaces, err := em.config.K8sClient.CoreV1().Namespaces().List(ctx, metav1.ListOptions{
		LabelSelector: "gtoken.doit-intl.com/ecr-managed=true",
	})
	if err != nil {
		em.metrics.RecordError("refresh_all_namespaces", "list_failed")
		return fmt.Errorf("failed to list ECR-managed namespaces: %w", err)
	}

	// Record number of managed namespaces
	em.metrics.RecordManagedNamespaces(len(namespaces.Items))

	for _, namespace := range namespaces.Items {
		err := em.CopySecretToNamespace(ctx, namespace.Name)
		if err != nil {
			log.Printf("Failed to refresh ECR secret in namespace %s: %v", namespace.Name, err)
			// Continue with other namespaces even if one fails
		} else {
			log.Printf("Successfully refreshed ECR secret in namespace %s", namespace.Name)
		}
	}

	return nil
}

// UpdateTokenState updates the ConfigMap with current token state for disaster recovery
func (em *ecrManager) UpdateTokenState(ctx context.Context, token string, expiresAt time.Time) error {
	// Use exponential backoff for ConfigMap operations
	return RetryWithBackoff(ctx, DefaultBackoffConfig(), func() error {
		return em.updateTokenStateOnce(ctx, token, expiresAt)
	})
}

// updateTokenStateOnce performs a single ConfigMap update operation
func (em *ecrManager) updateTokenStateOnce(ctx context.Context, token string, expiresAt time.Time) error {
	// Create token hash for change tracking
	tokenHash := fmt.Sprintf("%x", sha256.Sum256([]byte(token)))

	// Create or update ConfigMap
	configMap := &corev1.ConfigMap{
		ObjectMeta: metav1.ObjectMeta{
			Name:      "ecr-token-state",
			Namespace: em.config.GTokenNS,
			Labels: map[string]string{
				"app":       "gtoken-webhook",
				"component": "ecr-manager",
			},
		},
		Data: map[string]string{
			"token-hash":    tokenHash,
			"expires-at":    expiresAt.Format(time.RFC3339),
			"last-updated":  time.Now().Format(time.RFC3339),
			"token-version": fmt.Sprintf("%d", time.Now().Unix()),
		},
	}

	// Use Create/Update for idempotency (server-side apply requires applyconfigurations)
	existing, err := em.config.K8sClient.CoreV1().ConfigMaps(em.config.GTokenNS).Get(ctx, "ecr-token-state", metav1.GetOptions{})
	if err != nil {
		// ConfigMap doesn't exist, create it
		_, err = em.config.K8sClient.CoreV1().ConfigMaps(em.config.GTokenNS).Create(ctx, configMap, metav1.CreateOptions{})
		if err != nil {
			return fmt.Errorf("failed to create token state ConfigMap: %w", err)
		}
	} else {
		// ConfigMap exists, update it
		existing.Data = configMap.Data
		_, err = em.config.K8sClient.CoreV1().ConfigMaps(em.config.GTokenNS).Update(ctx, existing, metav1.UpdateOptions{})
		if err != nil {
			return fmt.Errorf("failed to update token state ConfigMap: %w", err)
		}
	}

	log.Printf("Updated token state ConfigMap with hash: %s, expires: %s", tokenHash, expiresAt.Format(time.RFC3339))
	return nil
}

// GetTokenState retrieves the current token state from ConfigMap
func (em *ecrManager) GetTokenState(ctx context.Context) (string, time.Time, error) {
	configMap, err := em.config.K8sClient.CoreV1().ConfigMaps(em.config.GTokenNS).Get(ctx, "ecr-token-state", metav1.GetOptions{})
	if err != nil {
		return "", time.Time{}, fmt.Errorf("failed to get token state ConfigMap: %w", err)
	}

	tokenHash, ok := configMap.Data["token-hash"]
	if !ok {
		return "", time.Time{}, fmt.Errorf("token-hash not found in ConfigMap")
	}

	expiresAtStr, ok := configMap.Data["expires-at"]
	if !ok {
		return "", time.Time{}, fmt.Errorf("expires-at not found in ConfigMap")
	}

	expiresAt, err := time.Parse(time.RFC3339, expiresAtStr)
	if err != nil {
		return "", time.Time{}, fmt.Errorf("failed to parse expires-at: %w", err)
	}

	return tokenHash, expiresAt, nil
}

// GetSecretTokenVersion retrieves the ecr-token-version annotation from a secret
func (em *ecrManager) GetSecretTokenVersion(ctx context.Context, namespace string) (string, error) {
	// Get the secret from the namespace
	secret, err := em.config.K8sClient.CoreV1().Secrets(namespace).Get(ctx, em.config.ECRSecretName, metav1.GetOptions{})
	if err != nil {
		return "", fmt.Errorf("failed to get ECR secret: %w", err)
	}

	// Check if the secret has the ecr-token-version annotation
	if secret.Annotations == nil {
		return "", fmt.Errorf("secret has no annotations")
	}

	tokenVersion, exists := secret.Annotations["ecr-token-version"]
	if !exists {
		return "", fmt.Errorf("secret missing ecr-token-version annotation")
	}

	return tokenVersion, nil
}
