// ECRManager handles ECR token generation and secret management
type ECRManager interface {
	// GetECRToken generates a new ECR authorization token
	GetECRToken(ctx context.Context) (string, time.Time, error)

	// CreateMasterSecret creates or updates the master ECR secret in the gtoken namespace
	CreateMasterSecret(ctx context.Context, token string) error

	// AddECRRegistryToMaster adds a new ECR registry to the master secret
	AddECRRegistryToMaster(ctx context.Context, registryURL, token string) error

	// CopySecretToNamespace copies the ECR secret to a target namespace
	CopySecretToNamespace(ctx context.Context, namespace string) error

	// ValidateSecret checks if a secret exists and is valid in a namespace
	ValidateSecret(ctx context.Context, namespace string) (bool, error)

	// StartTokenRefresh starts the background token refresh goroutine
	StartTokenRefresh(ctx context.Context) error

	// Stop stops the token refresh goroutine
	Stop()

	// RefreshAllNamespaces updates ECR secrets in all tracked namespaces
	RefreshAllNamespaces(ctx context.Context, token string) error

	// UpdateTokenState updates the ConfigMap with current token state for disaster recovery
	UpdateTokenState(ctx context.Context, token string, expiresAt time.Time) error

	// GetTokenState retrieves the current token state from ConfigMap
	GetTokenState(ctx context.Context) (string, time.Time, error)

	// GetSecretTokenVersion retrieves the ecr-token-version annotation from a secret
	GetSecretTokenVersion(ctx context.Context, namespace string) (string, error)
}

// ECRManagerConfig holds configuration for the ECR manager
type ECRManagerConfig struct {
	K8sClient     kubernetes.Interface
	GTokenNS      string
	ECRSecretName string
	RefreshBuffer time.Duration
	// ECR-specific configuration
	ECRRoleARN    string
	GTokenImage   string
	TokenFilePath string
}

// ecrManager implements ECRManager
type ecrManager struct {
	config    ECRManagerConfig
	stopChan  chan struct{}
	tokenChan chan string
	stopped   bool
	metrics   *ECRMetrics
}

// NewECRManager creates a new ECR manager instance
func NewECRManager(cfg *ECRManagerConfig) ECRManager {
	return &ecrManager{
		config:    *cfg,
		stopChan:  make(chan struct{}),
		tokenChan: make(chan string, 1),
		metrics:   NewECRMetrics(),
	}
}

// GetECRToken generates a new ECR authorization token
func (em *ecrManager) GetECRToken(ctx context.Context) (string, time.Time, error) {
	start := time.Now()
	var token string
	var expiresAt time.Time

	// Use exponential backoff for ECR token pull
	err := RetryWithBackoff(ctx, DefaultBackoffConfig(), func() error {
		var err error
		token, expiresAt, err = em.getECRTokenOnce(ctx)
		return err
	})

	duration := time.Since(start)
	if err != nil {
		em.metrics.RecordTokenRefresh("failure", duration)
		em.metrics.RecordTokenFetchError()
		return "", time.Time{}, fmt.Errorf("failed to get ECR authorization token after retries: %w", err)
	}

	em.metrics.RecordTokenRefresh("success", duration)
	em.metrics.RecordTokenExpiry(expiresAt)
	return token, expiresAt, nil
}

// getECRTokenOnce performs a single ECR token retrieval attempt
func (em *ecrManager) getECRTokenOnce(ctx context.Context) (string, time.Time, error) {
	// The webhook reads AWS credentials from the shared volume (generated by its own sidecar)
	// Then uses those credentials to call ECR GetAuthorizationToken API

	// Check if token file exists
	if em.config.TokenFilePath == "" {
		return "", time.Time{}, fmt.Errorf("token file path not configured")
	}

	// Set environment variables for AWS credentials from the token file
	os.Setenv("AWS_WEB_IDENTITY_TOKEN_FILE", em.config.TokenFilePath)
	if em.config.ECRRoleARN != "" {
		os.Setenv("AWS_ROLE_ARN", em.config.ECRRoleARN)
	}

	// Load AWS configuration that will use the web identity token
	cfg, err := config.LoadDefaultConfig(ctx)
	if err != nil {
		return "", time.Time{}, fmt.Errorf("failed to load AWS config: %w", err)
	}

	// Create ECR client
	ecrClient := ecr.NewFromConfig(cfg)

	// Call ECR GetAuthorizationToken
	result, err := ecrClient.GetAuthorizationToken(ctx, &ecr.GetAuthorizationTokenInput{})
	if err != nil {
		return "", time.Time{}, fmt.Errorf("failed to get ECR authorization token: %w", err)
	}

	// Check if we got any authorization data
	if len(result.AuthorizationData) == 0 {
		return "", time.Time{}, fmt.Errorf("no authorization data returned from ECR")
	}

	// Get the first authorization data (usually there's only one)
	authData := result.AuthorizationData[0]

	// Decode the authorization token (it's base64 encoded)
	token := aws.ToString(authData.AuthorizationToken)
	expiresAt := aws.ToTime(authData.ExpiresAt)

	return token, expiresAt, nil
}

// CreateMasterSecret creates or updates the master ECR secret in the gtoken namespace
func (em *ecrManager) CreateMasterSecret(ctx context.Context, token string) error {
	if token == "" {
		em.metrics.RecordError("create_master_secret", "empty_token")
		return fmt.Errorf("token cannot be empty")
	}

	// Get existing secret to preserve any existing ECR registries
	existingSecret, err := em.config.K8sClient.CoreV1().Secrets(em.config.GTokenNS).Get(ctx, em.config.ECRSecretName, metav1.GetOptions{})

	var existingAuths map[string]interface{}
	if err == nil && existingSecret.Data != nil {
		// Parse existing Docker config to preserve registries
		var existingConfig map[string]interface{}
		if err := json.Unmarshal(existingSecret.Data[".dockerconfigjson"], &existingConfig); err == nil {
			if auths, ok := existingConfig["auths"].(map[string]interface{}); ok {
				existingAuths = auths
			}
		}
	}

	// If no existing auths, create new map
	if existingAuths == nil {
		existingAuths = make(map[string]interface{})
	}

	// Update the ECR token for all existing ECR registries in CreateMasterSecret
	for registry := range existingAuths {
		if strings.Contains(registry, ".dkr.ecr.") && strings.Contains(registry, ".amazonaws.com") {
			// Remove https:// prefix if present for ECR registries
			cleanRegistry := strings.TrimPrefix(registry, "https://")

			// Fix: Decode the AWS token first (it comes base64 encoded)
			decodedToken, err := base64.StdEncoding.DecodeString(token)
			if err == nil {
				// Token was successfully decoded
				decodedStr := string(decodedToken)

				// Check if the decoded token already has AWS: prefix
				if strings.HasPrefix(decodedStr, "AWS:") {
					// Use the decoded token as-is
					existingAuths[cleanRegistry] = map[string]string{
						"auth": base64.StdEncoding.EncodeToString(decodedToken),
					}
				} else {
					// Add AWS: prefix to the decoded token
					existingAuths[cleanRegistry] = map[string]string{
						"auth": base64.StdEncoding.EncodeToString([]byte("AWS:" + decodedStr)),
					}
				}
			} else {
				// If decoding fails, use the token as-is (fallback)
				existingAuths[cleanRegistry] = map[string]string{
					"auth": token,
				}
			}

			// Remove the old entry with https:// prefix if it exists
			if registry != cleanRegistry {
				delete(existingAuths, registry)
			}
		}
	}

	// Create Docker config JSON with ECR token
	dockerConfig := map[string]interface{}{
		"auths": existingAuths,
	}

	dockerConfigJSON, err := json.Marshal(dockerConfig)
	if err != nil {
		return fmt.Errorf("failed to marshal docker config: %w", err)
	}

	// Generate token version for change tracking
	tokenVersion := fmt.Sprintf("%d", time.Now().Unix())

	// Create the secret
	secret := &corev1.Secret{
		ObjectMeta: metav1.ObjectMeta{
			Name:      em.config.ECRSecretName,
			Namespace: em.config.GTokenNS,
			Labels: map[string]string{
				"app":  "gtoken-webhook",
				"type": "ecr-secret",
			},
			Annotations: map[string]string{
				"ecr-token-version": tokenVersion,
			},
		},
		Type: corev1.SecretTypeDockerConfigJson,
		Data: map[string][]byte{
			".dockerconfigjson": dockerConfigJSON,
		},
	}

	// Try to create the secret, if it exists, update it
	_, err = em.config.K8sClient.CoreV1().Secrets(em.config.GTokenNS).Create(ctx, secret, metav1.CreateOptions{})
	if err != nil {
		// If secret already exists, update it
		_, err = em.config.K8sClient.CoreV1().Secrets(em.config.GTokenNS).Update(ctx, secret, metav1.UpdateOptions{})
		if err != nil {
			em.metrics.RecordError("create_master_secret", "update_failed")
			return fmt.Errorf("failed to create/update master ECR secret: %w", err)
		}
	}

	// Record token version metric
	if secret.Annotations != nil {
		tokenVersion := secret.Annotations["ecr-token-version"]
		em.metrics.RecordTokenVersion(tokenVersion)
	}

	return nil
}

// CreateECRSecretForRegistry creates an ECR secret for a specific registry in a namespace
func (em *ecrManager) CreateECRSecretForRegistry(ctx context.Context, namespace, registryURL, token string) error {
	if token == "" {
		em.metrics.RecordError("create_ecr_secret", "empty_token")
		return fmt.Errorf("token cannot be empty")
	}

	if registryURL == "" {
		em.metrics.RecordError("create_ecr_secret", "empty_registry")
		return fmt.Errorf("registry URL cannot be empty")
	}

	// Create Docker config JSON with ECR token for the specific registry
	dockerConfig := map[string]interface{}{
		"auths": map[string]interface{}{
			registryURL: map[string]string{
				"auth": base64.StdEncoding.EncodeToString([]byte("AWS:" + token)),
			},
		},
	}

	dockerConfigJSON, err := json.Marshal(dockerConfig)
	if err != nil {
		return fmt.Errorf("failed to marshal docker config: %w", err)
	}

	// Generate token version for change tracking
	tokenVersion := fmt.Sprintf("%d", time.Now().Unix())

	// Create the secret
	secret := &corev1.Secret{
		ObjectMeta: metav1.ObjectMeta{
			Name:      em.config.ECRSecretName,
			Namespace: namespace,
			Labels: map[string]string{
				"app":      "gtoken-webhook",
				"type":     "ecr-secret",
				"registry": registryURL,
			},
			Annotations: map[string]string{
				"ecr-token-version": tokenVersion,
				"ecr-registry":      registryURL,
			},
		},
		Type: corev1.SecretTypeDockerConfigJson,
		Data: map[string][]byte{
			".dockerconfigjson": dockerConfigJSON,
		},
	}

	// Try to create the secret, if it exists, update it
	_, err = em.config.K8sClient.CoreV1().Secrets(namespace).Create(ctx, secret, metav1.CreateOptions{})
	if err != nil {
		// If secret already exists, update it
		_, err = em.config.K8sClient.CoreV1().Secrets(namespace).Update(ctx, secret, metav1.UpdateOptions{})
		if err != nil {
			em.metrics.RecordError("create_ecr_secret", "update_failed")
			return fmt.Errorf("failed to create/update ECR secret in namespace %s: %w", namespace, err)
		}
	}

	return nil
}

